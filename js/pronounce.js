/* Recorded country-name clips for the game.
   Files live at assets/audio/<lang>/<iso>-name.mp3 and are generated by
   scripts/generate_audio.py; speech synthesis is only a safety net. */
import { BY_ID } from './data.js';
import { countryName } from './utils.js';

let current = null;

export function countryNameSrc(id, lang) {
  const code = lang === 'zh' ? 'zh' : 'en';
  return `/assets/audio/${code}/${String(id || '').toLowerCase()}-name.mp3`;
}

function speakFallback(id, lang) {
  const synth = window.speechSynthesis;
  if (!synth || typeof window.SpeechSynthesisUtterance !== 'function') return;
  const country = BY_ID[id];
  if (!country) return;
  synth.cancel();
  const utter = new SpeechSynthesisUtterance(countryName(country));
  utter.lang = lang === 'zh' ? 'zh-CN' : 'en-US';
  utter.rate = 0.9;
  synth.speak(utter);
}

export function playCountryName(id, lang) {
  const audio = new Audio(countryNameSrc(id, lang));
  audio.preload = 'auto';
  if (current) {
    try { current.pause(); } catch { /* noop */ }
  }
  current = audio;
  const clear = () => { if (current === audio) current = null; };
  audio.addEventListener('ended', clear);
  const played = audio.play();
  if (played && typeof played.catch === 'function') {
    played.catch(() => { clear(); speakFallback(id, lang); });
  }
  return audio;
}
