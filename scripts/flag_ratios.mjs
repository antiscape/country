#!/usr/bin/env node
/* Write js/flag-ratios.js from the dimensions of assets/flags/*.png so the game
   can size each answer tile to the flag's real proportions instead of
   letterboxing every flag inside one fixed box. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DIR = path.join(ROOT, 'assets', 'flags');

const entries = fs.readdirSync(DIR)
  .filter((name) => name.endsWith('.png'))
  .map((name) => {
    const buf = fs.readFileSync(path.join(DIR, name));
    const width = buf.readUInt32BE(16);
    const height = buf.readUInt32BE(20);
    return [name.slice(0, -4).toUpperCase(), Number((width / height).toFixed(3))];
  })
  .sort((a, b) => a[0].localeCompare(b[0]));

const body = entries.map(([id, ratio]) => `  ${id}: ${ratio},`).join('\n');
fs.writeFileSync(
  path.join(ROOT, 'js', 'flag-ratios.js'),
  `/* Generated by scripts/flag_ratios.mjs — do not edit by hand. */\nexport const FLAG_RATIOS = {\n${body}\n};\n`,
);
console.log(`flag-ratios.js: ${entries.length} flags`);
